"""用户输入的总设参数 —— **唯一数据源**。

约定（见 AGENTS.md）：

- 单位一律 **SI**：N、m、s、kg、rad、K。
- 翼载 W/S 在内部一律使用 **N/m²**。注意参考文献（李为吉《飞机总体设计》
  表 2.9）以 9.8 N/m²（= kgf/m²）为单位，抄录数值时须换算。
- 每个字段都注明单位、含义与典型值来源。

默认值取自一架**双发涡扇支线客机**量级的算例，用于跑通流程与自检；
实际设计请按任务要求替换。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class DesignParams:
    """总设参数的唯一数据源。"""

    # ------------------------------------------------------------------
    # 任务与总体
    # ------------------------------------------------------------------
    takeoff_weight: float = 250_000.0
    """起飞总重 W_TO, N（≈ 25.5 t）。

    注意：**可行域与总重无关** —— 约束分析在 (W/S, T/W) 平面上进行，总重只通过
    ``W/S = W_TO/S`` 决定“当前设计点”落在平面上的哪个位置，不改变边界曲线。
    单独改本参数只会移动当前设计点，不会改变可行域的面积与形状。
    """

    wing_area: float = 95.0
    """机翼参考面积 S, m²。与 ``takeoff_weight`` 共同决定当前设计点的翼载 W_TO/S。"""

    takeoff_thrust: float = 90_000.0
    """海平面静止、最大油门下的安装推力 F0, N。

    与 ``takeoff_weight`` 共同确定「当前设计点」的推重比 ``T/W = F0/W_TO``。
    软件会把它画在图上，并校核它是否落在可行域内。默认值对应 T/W = 0.36。
    """

    # ------------------------------------------------------------------
    # 气动特性
    # ------------------------------------------------------------------
    aspect_ratio: float = 8.5
    """机翼展弦比 A。"""

    oswald_e: float = 0.88
    """奥斯瓦尔德效率因子 e。战斗机 ≈0.6；其他 ≈0.8（李为吉 2.4 节，p.19）。"""

    cd0_clean: float = 0.018
    """巡航构型零升阻力系数 C_D0。喷气机 ≈0.015；整流好的螺旋桨机 ≈0.020（p.19）。"""

    cl_max_takeoff: float = 1.7
    """起飞构型最大升力系数 C_Lmax,TO。"""

    cl_max_landing: float = 2.3
    """着陆构型最大升力系数 C_Lmax。带襟翼与前缘缝翼的常规运输机 ≈2.4（p.22）。"""

    ld_takeoff: float = 9.5
    """起飞滑跑状态升阻比 L/D。超音速机 5~6；亚音速机 8~10（p.20）。"""

    ld_cruise: float = 19.0
    """巡航升阻比 L/D（式 2.23 取 1/(L/D) 作为巡航推重比）。"""

    # ------------------------------------------------------------------
    # 起飞约束（式 2.27）
    # ------------------------------------------------------------------
    takeoff_ground_run: float = 1200.0
    """地面滑跑距离 L_TOG, m。"""

    ground_friction_mu: float = 0.03
    """地面摩擦因数 μ_G。干水泥 0.02；湿水泥 0.03；硬土 0.07；草地 0.08（表 2.8，p.20）。"""

    # ------------------------------------------------------------------
    # 爬升约束（式 2.24）
    # ------------------------------------------------------------------
    climb_gradient: float = 0.024
    """爬升梯度 G（= tan γ）。双发运输机第二阶段爬升梯度要求量级。"""

    # ------------------------------------------------------------------
    # 速度约束
    # ------------------------------------------------------------------
    max_level_speed: float = 250.0
    """最大平飞速度 v_max, m/s。"""

    altitude_max_speed: float = 11_000.0
    """最大平飞速度对应高度, m。"""

    cruise_speed: float = 225.0
    """巡航速度, m/s（备查，式 2.23 只用到升阻比）。"""

    # ------------------------------------------------------------------
    # 失速约束（式 2.33）
    # ------------------------------------------------------------------
    stall_speed: float = 60.0
    """允许的最大失速速度 V_S, m/s（60 m/s ≈ 216 km/h）。"""

    altitude_stall: float = 0.0
    """失速速度对应的计算高度, m（通常取海平面）。"""

    # ------------------------------------------------------------------
    # 机动约束（式 2.36）
    # ------------------------------------------------------------------
    load_factor_maneuver: float = 2.5
    """机动过载 n。运输机 ≈2.5；战斗机 8~9（p.23）。"""

    cl_max_maneuver: float = 0.9
    """格斗/机动状态最大升力系数。仅用简单后缘襟翼的战斗机 0.6~0.8（p.23）。"""

    maneuver_speed: float = 150.0
    """机动速度, m/s。"""

    altitude_maneuver: float = 5_000.0
    """机动高度, m。"""

    # ------------------------------------------------------------------
    # 升限约束（式 2.37）
    # ------------------------------------------------------------------
    ceiling_altitude: float = 12_000.0
    """升限高度 H, m。"""

    ceiling_speed: float = 240.0
    """升限处的飞行速度 v_a, m/s。"""

    cl_ceiling: float = 0.5
    """升限飞行时的升力系数 C_L。"""

    # ------------------------------------------------------------------
    # 阻力极曲线（刘虎 3.3.4 节，式 3.11 / 3.35）
    # ------------------------------------------------------------------
    polar_k2: float = 0.0
    """极曲线一次项系数 K2。初步分析可取 0（刘虎 3.3.4 节）。

    二次项系数 K1 = 1/(π A e) 由 aspect_ratio 与 oswald_e 推算，不单独列出，
    见 core.aero.induced_drag_factor。
    """

    # ------------------------------------------------------------------
    # 推力比 α 与瞬时重量比 β（刘虎 3.3.4 节，式 3.38~3.44 及图 3.11 / 3.12）
    # ------------------------------------------------------------------
    # α = 该状态安装推力 / 海平面静推力；β = 该状态重量 / 起飞重量。
    # 下面的 α 默认值按高涵道比涡扇的估算式求得（刘虎 式 3.38）：
    #     α = {0.568 + 0.25(1.2 - Ma)³} · σ^0.6
    # 见 core.aero.thrust_lapse_high_bypass_turbofan。
    # β 按图 3.12 民用运输机的典型值取。
    #
    # ⚠️ α 由工况（高度、速度、发动机类型）决定，**不是**常数：
    #    改动 *_altitude / *_speed / 发动机类型时，必须同步更新对应的 α，
    #    否则约束会被错估。换用其他发动机见式(3.39)~(3.44)。
    alpha_max_speed: float = 0.28
    """最大平飞速度工况（11 km、Ma 0.85）的推力比，式(3.38) 计算值 ≈ 0.279。"""
    beta_max_speed: float = 0.92

    alpha_climb: float = 0.49
    """爬升工况（5 km、Ma 0.47）的推力比，式(3.38) 计算值 ≈ 0.491。"""
    beta_climb: float = 0.96
    """爬升段重量比 β（图 3.12 民用运输机 ≈ 0.95）。"""

    alpha_acceleration: float = 0.47
    """加减速工况（5 km、Ma 0.55）的推力比，式(3.38) 计算值 ≈ 0.470。"""
    beta_acceleration: float = 0.94

    alpha_turn: float = 0.49
    """盘旋工况（5 km、Ma 0.47）的推力比，式(3.38) 计算值 ≈ 0.491。"""
    beta_turn: float = 0.85
    """盘旋状态重量比 β。李为吉 2.4 节亦指出格斗重量约为起飞重量的 85%（p.23）。"""

    beta_landing: float = 0.70
    """着陆重量比 β（图 3.12 民用运输机着陆 β ≈ 0.7）。"""

    # ------------------------------------------------------------------
    # 爬升率约束（刘虎 式 3.23）
    # ------------------------------------------------------------------
    climb_rate: float = 5.0
    """要求达到的爬升率 dh/dt, m/s。"""

    climb_altitude: float = 5_000.0
    """爬升率考核高度, m。"""

    climb_speed: float = 150.0
    """爬升率考核速度 V, m/s。"""

    # ------------------------------------------------------------------
    # 水平加减速约束（刘虎 式 3.25 / 3.26）
    # ------------------------------------------------------------------
    acceleration_speed_initial: float = 150.0
    """加减速起始速度, m/s。"""

    acceleration_speed_final: float = 200.0
    """加减速终止速度, m/s。"""

    acceleration_allowable_time: float = 60.0
    """允许的加减速时间 Δt, s。图定 150→200 m/s 用时 60 s，平均加速度约 0.083g。"""

    acceleration_altitude: float = 5_000.0
    """加减速考核高度, m。"""

    # ------------------------------------------------------------------
    # 着陆滑跑距离约束（刘虎 式 3.34）
    # ------------------------------------------------------------------
    landing_ground_run: float = 900.0
    """着陆地面滑跑距离 x_LGR, m。"""

    landing_friction_mu: float = 0.25
    """着陆摩擦阻力系数 μ。一般 0.2~0.3，无实验数据时可取 0.25（刘虎 p.42）。"""

    touchdown_speed_factor: float = 1.30
    """接地安全速度系数 k_TD = V_TD / V_s。一般取 1.25~1.30（刘虎 p.42）。"""
