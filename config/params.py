"""用户输入的总设参数 —— **唯一数据源**。

约定（见 AGENTS.md）：

- 单位一律 **SI**：N、m、s、kg、rad、K。
- 翼载 W/S 在内部一律使用 **N/m²**。注意参考文献（李为吉《飞机总体设计》
  表 2.9）以 9.8 N/m²（= kgf/m²）为单位，抄录数值时须换算。
- 每个字段都注明单位、含义与典型值来源。

默认值取自一架**双发涡扇支线客机**量级的算例，用于跑通流程与自检；
实际设计请按任务要求替换。
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class DesignParams:
    """总设参数的唯一数据源。"""

    # ------------------------------------------------------------------
    # 任务与总体
    # ------------------------------------------------------------------
    takeoff_weight: float = 250_000.0
    """起飞总重 W_TO, N（≈ 25.5 t）。"""

    wing_area: float = 60.0
    """机翼参考面积 S, m²。"""

    # ------------------------------------------------------------------
    # 气动特性
    # ------------------------------------------------------------------
    aspect_ratio: float = 9.0
    """机翼展弦比 A。"""

    oswald_e: float = 0.80
    """奥斯瓦尔德效率因子 e。战斗机 ≈0.6；其他 ≈0.8（李为吉 2.4 节，p.19）。"""

    cd0_clean: float = 0.020
    """巡航构型零升阻力系数 C_D0。喷气机 ≈0.015；整流好的螺旋桨机 ≈0.020（p.19）。"""

    cd_max_level_speed: float = 0.045
    """最大平飞速度状态下的阻力系数 C_D（式 2.31 使用，含诱导阻力在内的总阻力系数）。"""

    cl_max_takeoff: float = 1.8
    """起飞构型最大升力系数 C_Lmax,TO。"""

    cl_max_landing: float = 2.4
    """着陆构型最大升力系数 C_Lmax。带襟翼与前缘缝翼的常规运输机 ≈2.4（p.22）。"""

    ld_takeoff: float = 9.0
    """起飞滑跑状态升阻比 L/D。超音速机 5~6；亚音速机 8~10（p.20）。"""

    ld_cruise: float = 16.0
    """巡航升阻比 L/D（式 2.23 取 1/(L/D) 作为巡航推重比）。"""

    # ------------------------------------------------------------------
    # 起飞约束（式 2.27）
    # ------------------------------------------------------------------
    takeoff_ground_run: float = 1500.0
    """地面滑跑距离 L_TOG, m。"""

    ground_friction_mu: float = 0.02
    """地面摩擦因数 μ_G。干水泥 0.02；湿水泥 0.03；硬土 0.07；草地 0.08（表 2.8，p.20）。"""

    # ------------------------------------------------------------------
    # 爬升约束（式 2.24）
    # ------------------------------------------------------------------
    climb_gradient: float = 0.024
    """爬升梯度 G（= tan γ）。双发运输机第二阶段爬升梯度要求量级。"""

    # ------------------------------------------------------------------
    # 速度约束
    # ------------------------------------------------------------------
    max_level_speed: float = 250.0
    """最大平飞速度 v_max, m/s。"""

    altitude_max_speed: float = 11_000.0
    """最大平飞速度对应高度, m。"""

    cruise_speed: float = 230.0
    """巡航速度, m/s（备查，式 2.23 只用到升阻比）。"""

    # ------------------------------------------------------------------
    # 失速约束（式 2.33）
    # ------------------------------------------------------------------
    stall_speed: float = 60.0
    """允许的最大失速速度 V_S, m/s（60 m/s ≈ 216 km/h）。"""

    altitude_stall: float = 0.0
    """失速速度对应的计算高度, m（通常取海平面）。"""

    # ------------------------------------------------------------------
    # 机动约束（式 2.36）
    # ------------------------------------------------------------------
    load_factor_maneuver: float = 2.5
    """机动过载 n。运输机 ≈2.5；战斗机 8~9（p.23）。"""

    cl_max_maneuver: float = 0.9
    """格斗/机动状态最大升力系数。仅用简单后缘襟翼的战斗机 0.6~0.8（p.23）。"""

    maneuver_speed: float = 150.0
    """机动速度, m/s。"""

    altitude_maneuver: float = 5_000.0
    """机动高度, m。"""

    # ------------------------------------------------------------------
    # 升限约束（式 2.37）
    # ------------------------------------------------------------------
    ceiling_altitude: float = 12_000.0
    """升限高度 H, m。"""

    ceiling_speed: float = 240.0
    """升限处的飞行速度 v_a, m/s。"""

    cl_ceiling: float = 0.5
    """升限飞行时的升力系数 C_L。"""
